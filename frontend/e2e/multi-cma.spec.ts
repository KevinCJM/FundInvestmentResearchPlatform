async function commonSelection(page: Page, mandate: string) {
  await page.goto(`/pre-investment/saa/policy?alloc=${encodeURIComponent(fixture.allocation)}&mandate=${mandate}`)
  await page.getByRole('combobox', { name: 'CMA 使用方式', exact: true }).selectOption('compatible_all_models')
  for (const id of fixture.common_ids) await add(page, id)
  await expect(page.getByRole('button', { name: '确认使用等权', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '核对模型并进入共同配置', exact: true }).click()
}

