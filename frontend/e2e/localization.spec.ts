  const zh = asset.getByRole('gridcell', { name: 'axes.asset zh-CN' })
  await zh.focus()
  // Same plain-text clipboard payload used by Excel's rectangular copy.
  await zh.evaluate(element => { const data = new DataTransfer(); data.setData('text/plain', '资产类别\tAsset class\t資産'); element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, clipboardData: data })) })
