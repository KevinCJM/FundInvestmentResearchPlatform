import { test, expect, type Page } from '@playwright/test'
import { spawn, type ChildProcess } from 'node:child_process'
import { createServer } from 'node:net'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

let backend: ChildProcess | undefined
let apiRoot = ''
let logs = ''
const settingsPath = '/settings/language-terminology'
const termKey = 'variables.periods_per_year.label'

test.beforeAll(async ({ request }) => {
  test.setTimeout(120_000)
  const socket = createServer()
  await new Promise<void>((resolve, reject) => { socket.once('error', reject); socket.listen(0, '127.0.0.1', resolve) })
  const address = socket.address()
  if (!address || typeof address === 'string') throw new Error('No port available')
  await new Promise<void>(resolve => socket.close(() => resolve()))
  apiRoot = `http://127.0.0.1:${address.port}`
  backend = spawn(process.env.INDICATOR_TEST_PYTHON || 'python3', ['-m', 'uvicorn', 'localization_app:app', '--app-dir', 'tests', '--host', '127.0.0.1', '--port', String(address.port)], {
    cwd: path.resolve(process.cwd(), '../backend'), env: { ...process.env, ALL_PROXY: '', HTTP_PROXY: '', HTTPS_PROXY: '', NO_PROXY: '127.0.0.1,localhost' }, stdio: ['ignore', 'pipe', 'pipe'],
  })
  backend.stdout?.on('data', chunk => { logs = (logs + String(chunk)).slice(-6000) })
  backend.stderr?.on('data', chunk => { logs = (logs + String(chunk)).slice(-6000) })
  backend.on('error', error => { logs += error.message })
  await expect.poll(async () => {
    if (backend?.exitCode != null) throw new Error(logs)
    try { return (await request.get(`${apiRoot}/ready`, { timeout: 1000 })).ok() } catch { return false }
  }, { timeout: 100_000 }).toBe(true)
})
test.afterEach(async ({ page }) => {
  // Drain in-flight proxy handlers before Playwright disposes the request context.
  await page.unrouteAll({ behavior: 'wait' })
})
test.afterAll(async () => {
  if (!backend || backend.exitCode !== null) return
  const stopped = new Promise<void>(resolve => backend?.once('exit', () => resolve()))
  backend.kill('SIGTERM')
  await Promise.race([stopped, new Promise<void>(resolve => setTimeout(resolve, 10_000))])
  if (backend.exitCode === null) backend.kill('SIGKILL')
})
async function routeApi(page: Page) {
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url())
    if (!url.pathname.startsWith('/api/i18n') && !url.pathname.startsWith('/api/custom-indicators')) {
      // Unrelated page-shell APIs remain explicitly unavailable in this fixture.
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Outside localization test fixture' }) })
      return
    }
    const response = await route.fetch({ url: `${apiRoot}${url.pathname}${url.search}`, timeout: 90_000 })
    await route.fulfill({ response })
  })
}
test.beforeEach(async ({ page, request }) => {
  const current = await (await request.get(`${apiRoot}/api/i18n/settings`)).json()
  await request.post(`${apiRoot}/api/i18n/business/restore`, { data: { expected_revision: current.revision, target_revision: 0 } })
  await request.put(`${apiRoot}/api/i18n/preferences`, { data: { expected_revision: current.preferences_revision, default_locale: 'zh-CN' } })
  page.setDefaultTimeout(15_000)
  await routeApi(page)
})

async function businessTable(page: Page, key = termKey) {
  await page.getByRole('tab', { name: '业务翻译（可自定义）', exact: true }).click()
  await page.getByRole('searchbox', { name: '搜索词条' }).fill(key)
  const row = page.locator(`tr[data-entry-key="${key}"]`)
  await expect(row).toBeVisible()
  return row
}

