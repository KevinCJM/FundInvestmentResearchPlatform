test('inconsistent model floors produce a proof and no adoption action', async ({ page }, info) => {
  await commonSelection(page, fixture.conflict_mandate_id)
  const calculation = page.waitForResponse(response => response.url().includes('/policy/preview') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '比较符合目标的政策候选', exact: true }).click()
  const response = await calculation; expect(response.ok(), await response.text()).toBe(true)
  const result = await response.json()
  expect(result.compatibility.joint_solver.status).toBe('infeasible')
  expect(result.compatibility.joint_solver.phase_one_lower_bound).toBeGreaterThan(0)
  await expect(page.getByText('已证明：这些约束无法同时满足。', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '复核此候选', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '4. 确认与交接', exact: true })).toBeDisabled()
  await layout(page, info, 'common-infeasible')
})
