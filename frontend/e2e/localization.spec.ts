test('业务翻译导入预览、导出和历史恢复，系统表不会被导入修改', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  await page.goto(settingsPath)
  await businessTable(page)
  const packageData = { format_version: 1, scope: 'business', entries: [{ key: termKey, locale: 'zh-CN', value: '导入的年化期数' }] }
  const before = await (await page.request.get(`${apiRoot}/api/i18n/settings`)).json()
  await page.getByLabel('导入业务覆盖', { exact: true }).setInputFiles({ name: 'translations.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(packageData)) })
  const preview = page.getByRole('region', { name: '确认导入差异' })
  await expect(preview).toContainText('导入的年化期数')
  const uncommitted = await (await page.request.get(`${apiRoot}/api/i18n/settings`)).json()
  expect(uncommitted.revision).toBe(before.revision)
  const appliedPromise = page.waitForResponse(response => response.url().endsWith('/business/import/apply'))
  await preview.getByRole('button', { name: '确认并应用导入' }).click()
  expect((await appliedPromise).status()).toBe(200)
  await expect(page.getByText(/业务翻译已保存/)).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出业务覆盖', exact: true }).click()
  const download = await downloadPromise
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(exported.scope).toBe('business')
  expect(exported.entries).toContainEqual(packageData.entries[0])
  expect(exported.entries.every((item: { key: string }) => !item.key.startsWith('common.') && !item.key.startsWith('navigation.'))).toBe(true)
  await page.getByRole('tab', { name: '修改历史', exact: true }).click()
  const initial = page.locator('tbody tr').filter({ has: page.getByText('初始版本', { exact: true }) })
  await expect(initial).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await initial.getByRole('button', { name: '恢复此版本' }).click()
  await expect(page.getByText(/业务翻译已保存/)).toBeVisible()
  const restored = await (await page.request.get(`${apiRoot}/api/i18n/settings`)).json()
  expect(restored.revision).toBeGreaterThan(before.revision)
  expect(restored.overrides).toEqual({})
  await page.getByTestId('language-terminology').screenshot({ path: testInfo.outputPath('language-history.png') })
})

